# Builds the verses added in quran-add-*.tsv into the app:
#   js/data-quran-kb.js                   entries appended to QURAN_LIB, text taken from Tanzil (quran-simple)
#   build/i18n/content/quran-kb.json      English notes (verse meanings come from each language's full Tanzil translation)
# Each row: ref (surah:ayah or surah:a-b), expect (words that must be in the verse: guards against a wrong number),
# th (themes), w (usage time if it is a supplication), n_ar, n_en.
# Usage: python -I build/kb/build-quran.py [--check]
import io, json, os, re, sys, glob, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from kbsrc import *
sys.stdout.reconfigure(encoding="utf-8")
CHECK = "--check" in sys.argv
W_EN = {"في الصباح والمساء وعند النوم": "Morning, evening and at bedtime", "عند بداية جديدة": "At a new beginning", "عند الدراسة": "When studying",
        "ذكر يومي": "Daily remembrance", "في الصباح والمساء": "Morning and evening"}

app = load_app()
SNO, SURAHS = surah_names()
Q = load_quran()
THEMES = set(json.loads(subprocess.check_output(["node", "-e", 'const L=require(process.argv[1])(process.argv[2]);process.stdout.write(JSON.stringify(L.THEMES.map(t=>t.id)))',
                                              os.path.join(ROOT, "build", "tests", "load.js"), os.path.join(ROOT, "js")], encoding="utf-8")))
def verses(s, a):
    a = str(a).replace("–", "-"); x = a.split("-")
    return [(s, v) for v in range(int(x[0]), int(x[-1]) + 1)]
have = {}
for q in app["quran"]:
    for k in verses(SNO[norm_ar(q["s"])], q["a"]): have[k] = q["id"]
MARKS = re.compile(r"[ً-ْٰۖ-ۭـ]")
def plain(v):
    v = MARKS.sub("", v.replace("﻿", ""))
    v = v.replace("ٱ", "ا")
    return re.sub(r"\s+", " ", v).strip()

rows, errors, warns = [], [], []
for f in sorted(glob.glob(os.path.join(HERE, "quran-add-*.tsv"))):
    lines = io.open(f, encoding="utf-8").read().rstrip("\n").split("\n")
    head = lines[0].split("\t")
    for k, l in enumerate(lines[1:], 2):
        c = l.split("\t"); c += [""] * (len(head) - len(c))
        p = dict(zip(head, c)); p["_at"] = "%s:%d" % (os.path.basename(f), k); rows.append(p)

out, en, seen = [], {"quran": {}}, {}
for p in rows:
    at = p["_at"]
    try:
        s, a = p["ref"].split(":"); s = int(s); vv = verses(s, a)
    except Exception: errors.append(at + ": bad ref " + p["ref"]); continue
    if any(v < 1 or v > len(Q[s - 1]) for _, v in vv): errors.append(at + ": no such verse " + p["ref"]); continue
    text = " * ".join(plain(Q[s - 1][v - 1]) for _, v in vv)
    miss = [w for w in toks(p["expect"]) if w not in toks(text)]
    if miss: errors.append(at + ": %s does not contain «%s» → %s" % (p["ref"], " ".join(miss), text[:90])); continue
    dup = [have[k] for k in vv if k in have] + [seen[k] for k in vv if k in seen]
    if dup: errors.append(at + ": %s already in the library (%s)" % (p["ref"], ", ".join(sorted(set(dup))))); continue
    th = [t for t in p["th"].split(",") if t]
    bad = [t for t in th if t not in THEMES]
    if bad: errors.append(at + ": unknown theme " + ",".join(bad)); continue
    qid = "q%d-%d" % (s, vv[0][1])
    for k in vv: seen[k] = qid
    e = {"id": qid, "s": SURAHS[s - 1], "a": a, "t": text, "th": th, "n": p["n_ar"], "kb": 1}
    if p.get("w"): e["dua"] = True; e["w"] = p["w"]
    out.append(e)
    en["quran"][qid] = {"n": p["n_en"]}
    if p.get("w"):
        if p["w"] not in W_EN: errors.append(at + ": no English for usage time " + p["w"])
        en["quran"][qid]["w"] = W_EN.get(p["w"], p["w"])

print("verse rows:", len(rows), "→ built", len(out))
if warns: print("warnings:\n  " + "\n  ".join(warns))
if errors: print("ERRORS (%d):\n  " % len(errors) + "\n  ".join(errors)); sys.exit(1)
if CHECK: sys.exit(0)
J = lambda v: json.dumps(v, ensure_ascii=False)
js = ("/* GENERATED by build/kb/build-quran.py from build/kb/quran-add-*.tsv - do not edit by hand.\n"
      "   Verse text from Tanzil (quran-simple), without diacritics (the app shows them from Tanzil via data-tashkeel.js).\n"
      "   Each reference was checked against expected words before inclusion. Notes (n) are the app's own. */\n"
      "QURAN_LIB.push(\n" + ",\n".join(J(e) for e in out) + "\n);\n")
io.open(os.path.join(ROOT, "js", "data-quran-kb.js"), "w", encoding="utf-8", newline="\n").write(js)
io.open(os.path.join(ROOT, "build", "i18n", "content", "quran-kb.json"), "w", encoding="utf-8", newline="\n").write(json.dumps(en, ensure_ascii=False, indent=1) + "\n")
print("wrote js/data-quran-kb.js (%d KB), content/quran-kb.json" % (len(js.encode("utf-8")) // 1024))
