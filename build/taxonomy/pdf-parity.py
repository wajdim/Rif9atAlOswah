# -*- coding: utf-8 -*-
"""Parity check: the 500 life situations in js/data-life.js against the source PDF.

    python -I build/taxonomy/pdf-parity.py [path/to/500-life-situations-arabic.pdf] [--write]

- Extracts the PDF text with PyMuPDF (build-time only; `pip install pymupdf`).
  The PDF stores Arabic as presentation forms with reversed digit runs: text is NFKC-normalised
  and numbers are read right to left.
- Compares, for n = 1..500: presence, the text (letters only: no diacritics, punctuation or
  hamza-seat differences) and the section (s). Anything else is reported as a difference.
- Also checks that the taxonomy (build/taxonomy/life-NN.tsv) has exactly one row per situation.
- --write saves the report to build/taxonomy/PDF-PARITY.md.
Exit code 1 if any situation is missing or its text differs.
"""
import io, os, re, sys, unicodedata, difflib
H = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.normpath(os.path.join(H, "..", ".."))
sys.stdout.reconfigure(encoding="utf-8")
args = [a for a in sys.argv[1:] if not a.startswith("--")]
PDF = args[0] if args else os.path.join(ROOT, "docs", "500-life-situations-arabic.pdf")
WRITE = "--write" in sys.argv

AR_DIGITS = str.maketrans("٠١٢٣٤٥٦٧٨٩", "0123456789")
MARKS = re.compile(r"[ؐ-ًؚ-ٰٟۖ-ۭـ]")

def letters(t):
    t = unicodedata.normalize("NFKC", t)
    t = MARKS.sub("", t)
    t = re.sub(r"[أإآٱؤئ]", "ء", t).replace("ى", "ي").replace("ة", "ه")
    t = re.sub(r"[^ء-يa-zA-Z0-9]+", " ", t)
    return re.sub(r"\s+", " ", t).strip()

def pdf_lines(path):
    import pymupdf
    doc = pymupdf.open(path)
    out = []
    for page in doc:
        for ln in page.get_text().split("\n"):
            ln = unicodedata.normalize("NFKC", ln)
            ln = re.sub(r"[ក-៿]", "ً", ln)   # a tanween glyph the PDF maps into the Khmer block
            out.append(ln.strip())
    return out

def number(ln):
    """a line that is only a (right-to-left) Arabic-Indic number"""
    if re.fullmatch(r"[٠-٩]{1,3}", ln): return int(ln[::-1].translate(AR_DIGITS))
    return None

def parse(lines):
    """n -> (text, section title). Situations follow a line holding their number, in order 1..500."""
    items, expect, cur, buf, section = {}, 1, None, [], ""
    heads = set()
    for i, ln in enumerate(lines):
        n = number(ln)
        if n == expect and (cur is None or buf):
            if cur is not None: items[cur] = (" ".join(buf), section_of[cur])
            cur, buf, expect = n, [], n + 1
            section_of[cur] = section
            continue
        if ln.startswith("المواقف من") and i > 0: section = lines[i - 1]
        if cur is None or not ln: continue
        if buf and re.search(r"[.؟!»]$", buf[-1]): continue      # sentence complete: rest is page furniture
        if number(ln) is not None or "موقف من الحياة" in ln or "•" in ln: continue
        if ln.startswith("المواقف من") or ln == "إلى": continue          # page header «المواقف من N إلى M»
        buf.append(ln)
    if cur is not None: items[cur] = (" ".join(buf), section_of[cur])
    return items
section_of = {}

def app_life():
    src = io.open(os.path.join(ROOT, "js", "data-life.js"), encoding="utf-8").read()
    secs = dict(re.findall(r'"(\d+)":\s*"([^"]+)"', src.split("var LIFE =")[0]))
    rows = {int(n): (t, s) for n, s, t in re.findall(r'\{n:(\d+),s:(\d+),t:"((?:[^"\\]|\\.)*)"', src)}
    return rows, secs

def taxonomy_rows():
    seen = {}
    for f in sorted(os.listdir(H)):
        if re.fullmatch(r"life-\d\d\.tsv", f):
            for ln in io.open(os.path.join(H, f), encoding="utf-8").read().splitlines()[1:]:
                if ln.strip():
                    n = int(ln.split("\t", 1)[0]); seen[n] = seen.get(n, 0) + 1
    return seen

if not os.path.exists(PDF):
    print("PDF not found: " + PDF); sys.exit(2)
pdf = parse(pdf_lines(PDF))
app, secs = app_life()
tax = taxonomy_rows()
missing_pdf = [n for n in range(1, 501) if n not in pdf]
missing_app = [n for n in range(1, 501) if n not in app]
same, near, diff, secdiff, seccmp = [], [], [], [], 0
for n in range(1, 501):
    if n not in pdf or n not in app: continue
    a, b = letters(pdf[n][0]), letters(app[n][0])
    if a == b: same.append(n)
    else:
        r = difflib.SequenceMatcher(None, a, b).ratio()
        (near if r >= 0.9 else diff).append((n, r, pdf[n][0], app[n][0]))
    ps = letters(pdf[n][1]); asec = letters(secs.get(app[n][1], ""))
    if ps and asec: seccmp += 1
    if ps and asec and ps != asec and asec not in ps and ps not in asec: secdiff.append((n, pdf[n][1], secs.get(app[n][1], "")))
tax_bad = [n for n in range(1, 501) if tax.get(n) != 1]

L = ["# Life situations: parity with the source PDF", "",
     "Generated by `python -I build/taxonomy/pdf-parity.py --write` from `%s`." % os.path.basename(PDF), "",
     "| check | result |", "|---|---|",
     "| situations found in the PDF | %d / 500 |" % (500 - len(missing_pdf)),
     "| situations in `js/data-life.js` | %d / 500 |" % (500 - len(missing_app)),
     "| identical text (letters only) | %d |" % len(same),
     "| near-identical (≥ 90%%, spelling or punctuation) | %d |" % len(near),
     "| different text | %d |" % len(diff),
     "| section differs | %d (of %d whose PDF page header could be read) |" % (len(secdiff), seccmp),
     "| taxonomy rows (one per situation 1–500) | %s |" % ("ok" if not tax_bad else "%d wrong" % len(tax_bad)), ""]
if missing_pdf: L += ["Not found in the PDF: " + ", ".join(map(str, missing_pdf)), ""]
if missing_app: L += ["Missing from the app: " + ", ".join(map(str, missing_app)), ""]
for title, rows in [("Near-identical", near), ("Different", diff)]:
    if rows:
        L += ["## " + title, "", "| n | similarity | PDF | app |", "|---|---|---|---|"]
        L += ["| %d | %.2f | %s | %s |" % (n, r, p, a) for n, r, p, a in rows] + [""]
if secdiff:
    L += ["## Section differences", "", "| n | PDF | app |", "|---|---|---|"] + ["| %d | %s | %s |" % x for x in secdiff] + [""]
if tax_bad: L += ["Taxonomy rows missing or duplicated for: " + ", ".join(map(str, tax_bad[:50])), ""]
report = "\n".join(L)
print(report)
if WRITE: io.open(os.path.join(H, "PDF-PARITY.md"), "w", encoding="utf-8", newline="\n").write(report + "\n")
sys.exit(1 if (missing_pdf or missing_app or diff or tax_bad) else 0)
