/* ======================================================================
   رِفقة الأُسوة — بناء ملف اللغة الإنجليزية js/data-en.js
   المدخلات:
   - build/i18n/ui-en.json            : قاموس نصوص الواجهة (عربي ← إنجليزي)
   - build/i18n/src/en.sahih.txt      : معاني القرآن (Saheeh International، Tanzil.net)
                                        تُضمَّن فقط الآيات المستعملة في التطبيق
   - build/i18n/content/*.json        : ترجمة المحتوى، يُدمج بالترتيب:
       sit-*.json   {sit:{id:{...}}}    themes*.json {theme:{id:{...}}}
       quran*.json  {quran:{id:{n,w}}}  hadith*.json {hadith:{id:{te,n,w,r}}}
       lexicon.json {lexicon:{emotion,relation,intensifiers,selfFault}}
   الاستخدام: node build/i18n/build-en.js [en|nl]
     nl: ui-nl.json و src/nl.siregar.txt و nl/content/*.json ← js/data-nl.js (NL_DATA)
   ====================================================================== */
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.join(__dirname, "..", "..");
const LANG = process.argv[2] === "nl" ? "nl" : "en";
const L = {
  en: { quran: "en.sahih.txt", content: "content", ui: "ui-en.json", out: "data-en.js", v: "EN_DATA",
        head: "English. Generated by build/i18n/build-en.js.\n   Quran meanings: Saheeh International (Tanzil.net). Hadith translations follow sunnah.com (hadith-json)." },
  nl: { quran: "nl.siregar.txt", content: path.join("nl", "content"), ui: "ui-nl.json", out: "data-nl.js", v: "NL_DATA",
        head: "Nederlands. Generated by build/i18n/build-en.js nl.\n   Koranbetekenissen: Sofian S. Siregar (Tanzil.net). Hadithvertalingen: eigen vertaling naar de Engelse tekst van sunnah.com." }
}[LANG];
const ctx = { window: {}, console }; ctx.window = ctx; vm.createContext(ctx);
for (const f of ["data-situations", "data-situations-2", "data-situations-3", "data-situations-4", "data-quran", "data-hadith", "data-themes"])
  vm.runInContext(fs.readFileSync(path.join(ROOT, "js", f + ".js"), "utf8").replace(/^(const|let) /gm, "var "), ctx);
const ictx = { window: {}, localStorage: { getItem: () => '{"lang":"en"}' }, document: {}, navigator: {} }; ictx.window = ictx;
vm.createContext(ictx); vm.runInContext("var EN_DATA={quran:{}};" + fs.readFileSync(path.join(ROOT, "js", "i18n.js"), "utf8"), ictx);

// 1) القرآن: الآيات المستعملة فقط
const all = {};
for (const line of fs.readFileSync(path.join(__dirname, "src", L.quran), "utf8").split(/\r?\n/)) {
  const m = line.match(/^(\d+)\|(\d+)\|(.*)$/); if (m) all[m[1] + ":" + m[2]] = m[3].trim();
}
const SN = s => { const r = ictx.I18N.ref(s, "1").match(/ (\d+):1$/); return r ? +r[1] : 0; };
const quran = {}, missQ = [];
function want(s, a) {
  const n = SN(s), m = String(a).match(/(\d+)(?:\s*[-–]\s*(\d+))?/);
  if (!n || !m) { missQ.push(s + " " + a); return; }
  for (let i = +m[1]; i <= (m[2] ? +m[2] : +m[1]); i++) { const k = n + ":" + i; if (all[k]) quran[k] = all[k]; else missQ.push(k); }
}
ctx.QURAN_LIB.forEach(q => want(q.s, q.a));
ctx.SITUATIONS.forEach(s => (s.quranRefs || []).forEach(q => want(q.surahName, q.ayahNumber)));

// 2) المحتوى
const content = { sit: {}, theme: {}, quran: {}, hadith: {}, lexicon: {} };
const cdir = path.join(__dirname, L.content);
for (const f of fs.readdirSync(cdir).filter(f => f.endsWith(".json")).sort()) {
  const d = JSON.parse(fs.readFileSync(path.join(cdir, f), "utf8"));
  for (const k of Object.keys(d)) Object.assign(content[k] = content[k] || {}, d[k]);
}
// ترجمات نصوص الأحاديث (hadith-te-*.json): «lib:id» لمكتبة الأحاديث، «sit:id:i» لأحاديث المواقف
for (const [key, te] of Object.entries(content.te || {})) {
  const p = key.split(":");
  if (p[0] === "lib") (content.hadith[p[1]] = content.hadith[p[1]] || {}).te = te;
  else if (p[0] === "sit") {
    const s = content.sit[p[1]] = content.sit[p[1]] || {}, i = +p[2];
    s.hadithRefs = s.hadithRefs || []; s.hadithRefs[i] = Object.assign(s.hadithRefs[i] || {}, { te });
  }
}
delete content.te;
const ui = JSON.parse(fs.readFileSync(path.join(__dirname, L.ui), "utf8"));

// 3) تقرير التغطية
const ids = a => a.map(x => x.id);
const cov = (name, list, map) => { const have = ids(list).filter(i => map[i]).length; return name + " " + have + "/" + list.length; };
const hadithTe = ctx.HADITH_LIB.filter(h => (content.hadith[h.id] || {}).te).length;
const sitHad = ctx.SITUATIONS.reduce((a, s) => a + (s.hadithRefs || []).length, 0);
const sitHadTe = ctx.SITUATIONS.reduce((a, s) => a + ((content.sit[s.id] || {}).hadithRefs || []).filter(x => x && x.te).length, 0);
fs.writeFileSync(path.join(ROOT, "js", L.out),
  "/* رِفقة الأُسوة — " + L.head + " */\n" +
  "var " + L.v + "=" + JSON.stringify({ ui, quran, content }) + ";\n");
console.log("[" + LANG + "] ui " + Object.keys(ui).length + " · quran ayat " + Object.keys(quran).length + (missQ.length ? " (missing " + missQ.join(", ") + ")" : "") +
  " · " + cov("sits", ctx.SITUATIONS, content.sit) + " · " + cov("themes", ctx.THEMES, content.theme) +
  " · " + cov("quran notes", ctx.QURAN_LIB, content.quran) + " · hadith te " + hadithTe + "/" + ctx.HADITH_LIB.length +
  " · sit hadith te " + sitHadTe + "/" + sitHad);
